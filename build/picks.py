"""The multiple-choice answers for every "What goes next?" question in the course.

Each question shows its line with one or two blanks, written ____, and three choices.
A wrong choice opens one sentence that says why it does not fit. The right choice opens
the finished line and a short explanation of why that code is right for this program.

PICKS maps a ladder's tag (session, then chunk or tool) to one entry per step, in the
order of the steps in the session's generator. An entry holds:

    right   what goes in the blank; a tuple when the line has two blanks
    wrong   two (fill, why it does not fit) pairs
    why     why the finished line is right for this program
    blank   optional: the line with ____ in it, when it should differ from the one the
            step's last hint carries (render.py uses that one by default). It may be a
            function that takes the finished line and returns it with a blank.
    text    optional, True when the choices are sentences and the question has no blank

render.py fills the blank with each choice and stops the build unless the right one
gives exactly the step's line and each wrong one gives something else.
"""


def stage4_blank(line):
    """Session 8's list of pictures, with the arms of stage 4 left blank."""
    arms = ' -|-  |\\n      |'
    assert line.count(arms) == 1
    return line.replace(arms, ' ____  |\\n      |')


